// ============================================================================
// test_softmax_argmax.cpp — Softmax、SiLU、Argmax 算子的单元测试
// ============================================================================
// 本文件测试三个基础算子的实现正确性：
//
//   1. Softmax：将 logits 转换为概率分布
//      - 已知值手动验证
//      - 数值稳定性（大数偏移不变性）
//
//   2. SiLU（Sigmoid Linear Unit）：激活函数
//      - 已知值手动验证（x * sigmoid(x)）
//
//   3. Argmax：找出最大值的索引
//      - 基本功能
//      - 平局时取第一个最大值
//
// 这些是 LLM 推理中最基础的非线性算子，Silu 用于门控 MLP，
// Softmax 用于 attention 权重归一化，Argmax 用于 token 采样。
// ============================================================================

#include "test_framework.h"

#include <cmath>

#include "ref_ops.h"

using namespace tinyqwen;

// =========================================================================
//  Softmax 测试
// =========================================================================

// ---------------------------------------------------------------------------
// 测试：Softmax 已知值手动验证
//
// 输入 [1, 2, 3]，softmax 公式：p_i = exp(x_i) / sum(exp(x))
// exp(1)=2.71828, exp(2)=7.38906, exp(3)=20.0855
// sum = 30.1929
// p0 = 2.71828/30.1929 = 0.0900306
// p1 = 7.38906/30.1929 = 0.2447285
// p2 = 20.0855/30.1929 = 0.6652409
// 验证 sum = 1.0（概率分布）
// ---------------------------------------------------------------------------
TEST (softmax_known_values) {
    const float x[3] = {1, 2, 3}; // 输入 logits
    float y[3];                     // 输出概率

    softmax_ref(x, y, 3);

    // 手工计算的期望值
    EXPECT_NEAR(y[0], 0.0900306, 1e-6);
    EXPECT_NEAR(y[1], 0.2447285, 1e-6);
    EXPECT_NEAR(y[2], 0.6652409, 1e-6);

    // 概率之和必须为 1.0
    EXPECT_NEAR(y[0] + y[1] + y[2], 1.0, 1e-6);
}

// ---------------------------------------------------------------------------
// 测试：Softmax 数值稳定性 —— 大数偏移不变性
//
// 所有输入加同一个常数，softmax 输出不应改变。
// 同时验证大数（1000.0）不会导致上溢（overflow）。
//
// 原理：softmax(x + c) = softmax(x)，因为 exp(x_i + c) / sum(exp(x_j + c))
// = exp(x_i) * exp(c) / (sum(exp(x_j)) * exp(c)) = exp(x_i) / sum(exp(x_j))
// = softmax(x)
// 实现中通常用 max(x) 作为偏移量来保证数值稳定性。
// ---------------------------------------------------------------------------
TEST (softmax_stability_with_large_offset) {
    // 所有输入加同一个常数，输出不应改变（同时验证大数不上溢）。
    const float a[2] = {1000.0f, 1001.0f}; // 大数版本
    const float b[2] = {0.0f, 1.0f};       // 小数版本（减去 1000 后）

    float ya[2], yb[2];
    softmax_ref(a, ya, 2);
    softmax_ref(b, yb, 2);

    const double e = std::exp(1.0);

    // 小数版本验证
    EXPECT_NEAR(ya[0], 1.0 / (1.0 + e), 1e-6);
    EXPECT_NEAR(ya[1], e / (1.0 + e), 1e-6);

    // 大数版本和小数版本应输出相同结果（偏移不变性）
    EXPECT_NEAR(ya[0], yb[0], 1e-6);
    EXPECT_NEAR(ya[1], yb[1], 1e-6);
}

// =========================================================================
//  SiLU（Sigmoid Linear Unit）激活函数测试
// =========================================================================

// ---------------------------------------------------------------------------
// 测试：SiLU 已知值手动验证
//
// SiLU(x) = x * sigmoid(x)，其中 sigmoid(x) = 1 / (1 + exp(-x))
//
// SiLU(0) = 0 * 0.5 = 0.0
// SiLU(1) = 1 * sigmoid(1) = 1 * 0.7310585786300049 = 0.73105858
// SiLU(-1) = -1 * sigmoid(-1) = -1 * 0.2689414213699951 = -0.26894142
//
// SiLU（也叫 Swish）是 Qwen 模型使用的激活函数，相比 ReLU 更平滑，
// 在负数区域有非零梯度，有助于训练稳定性和推理精度。
// ---------------------------------------------------------------------------
TEST (silu_known_values) {
    const float x[3] = {0.0f, 1.0f, -1.0f}; // 测试输入
    float y[3];                                 // 输出

    silu_ref(x, y, 3);

    // SiLU(0) = 0 * 0.5 = 0
    EXPECT_NEAR(y[0], 0.0, 1e-6);

    // SiLU(1) = 1 * sigmoid(1) ≈ 0.7310586
    EXPECT_NEAR(y[1], 0.7310586, 1e-6);

    // SiLU(-1) = -1 * sigmoid(-1) ≈ -0.2689414
    EXPECT_NEAR(y[2], -0.2689414, 1e-6);
}

// =========================================================================
//  Argmax 测试
// =========================================================================

// ---------------------------------------------------------------------------
// 测试：Argmax 基本功能
//
// 找到数组中最大值的索引。如果有多个最大值，返回第一个（最小值索引）。
// ---------------------------------------------------------------------------
TEST (argmax_basic) {
    // 测试数组：[0.1, 3.0, -2.0, 3.0, 1.5]
    const float logits[5] = {0.1f, 3.0f, -2.0f, 3.0f, 1.5f};

    // 最大值是 3.0，出现在索引 1 和 3，应返回第一个（索引 1）
    EXPECT_EQ(argmax_ref(logits, 5), 1);

    // 单元素数组：唯一元素就是最大值
    const float single[1] = {42.0f};
    EXPECT_EQ(argmax_ref(single, 1), 0);
}