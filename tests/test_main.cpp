// =============================================================================
// test_main.cpp — 单元测试统一入口
// =============================================================================
// 本文件是 tinyqwen 项目所有单元测试的统一入口。它不包含任何具体测试逻辑，
// 仅负责调用 tinytest 测试框架的 run_all() 函数，将所有通过 TEST() 宏注册
// 的测试用例集中执行，并返回退出码。
//
// 测试框架：
//   - tinytest 是一个轻量级 C++ 测试框架（定义在 test_framework.h 中）。
//   - 每个 .cpp 文件中的 TEST(name) 宏会在全局构造函数阶段自动注册用例。
//   - run_all() 遍历所有已注册的用例并依次执行，汇总通过/失败数量。
//
// 退出码约定：
//   - 0: 所有测试用例通过
//   - 1: 至少有一个测试用例失败
//   该约定符合 CI/CD 流水线的标准返回码规范。
// =============================================================================

#include "test_framework.h"

// 测试主入口：调用 tinytest 框架运行所有已注册的测试用例
// 返回 0 表示全部通过，返回 1 表示有失败
int main() { return tinytest::run_all() == 0 ? 0 : 1; }