// ============================================================================
// test_rmsnorm.cpp — RMSNorm（Root Mean Square Normalization）算子的单元测试
// ============================================================================
// 本文件测试 rmsnorm_ref 实现的正确性，包括：
//   1. 小规模手动计算验证
//   2. 尺度不变性（输入 x 缩放后，归一化结果不变）
//   3. 权重向量（w）对归一化结果的影响
//
// RMSNorm 是 LLM 中最常用的归一化算子之一，公式为：
//   y_i = x_i / sqrt(mean(x^2) + eps) * w_i
// 其中 mean(x^2) = sum(x_i^2) / N，eps 是防除零的小常数，
// w 是可学习的逐元素权重向量。
// ============================================================================

#include "test_framework.h"

#include <cmath>
#include <vector>

#include "ref_ops.h"

using namespace tinyqwen;

// ---------------------------------------------------------------------------
// 测试：小规模 RMSNorm 手动计算
//
// x = [1, 2, 3], w = [1, 1, 1], eps = 1e-6
// mean(x^2) = (1+4+9)/3 = 14/3
// y = x / sqrt(14/3 + 1e-6)
// 手工计算每个元素的值并与实现对比。
// ---------------------------------------------------------------------------
TEST (rmsnorm_small) {
    const float x[3] = {1.0f, 2.0f, 3.0f};      // 输入向量
    const float w[3] = {1.0f, 1.0f, 1.0f};       // 权重向量（全 1，不影响结果）
    float y[3];                                    // 输出缓冲区

    rmsnorm_ref(x, w, y, 3, 1e-6f);

    // mean(x^2) = 14/3；y = x / sqrt(14/3 + 1e-6)
    const double scale = 1.0 / std::sqrt(14.0 / 3.0 + 1e-6);

    // 逐元素验证
    EXPECT_NEAR(y[0], 1.0 * scale, 1e-5);
    EXPECT_NEAR(y[1], 2.0 * scale, 1e-5);
    EXPECT_NEAR(y[2], 3.0 * scale, 1e-5);
}

// ---------------------------------------------------------------------------
// 测试：RMSNorm 的尺度不变性
//
// 缩放输入 x 不应该改变归一化后的方向（RMSNorm 是尺度不变的）。
// 即：RMSNorm(α * x) = RMSNorm(x) 对任意非零 α 成立。
// 这是因为归一化过程中会除以 sqrt(mean(x^2))，α 会被约掉。
// ---------------------------------------------------------------------------
TEST (rmsnorm_weight_and_scale) {
    // 缩放 x 不应改变归一化后的方向（RMSNorm 是尺度不变的）。
    const float w[4] = {1.0f, 2.0f, 0.5f, 4.0f}; // 权重向量
    float y1[4], y2[4];

    // 原始输入
    const float x1[4] = {0.5f, -1.5f, 2.0f, 0.25f};

    // 缩放后的输入（乘以 7.0）
    float x2[4];
    for (int i = 0; i < 4; ++i) x2[i] = x1[i] * 7.0f;

    // 对两个输入分别计算 RMSNorm
    rmsnorm_ref(x1, w, y1, 4, 1e-6f);
    rmsnorm_ref(x2, w, y2, 4, 1e-6f);

    // 结果应该完全相同（尺度不变性）
    for (int i = 0; i < 4; ++i) EXPECT_NEAR(y1[i], y2[i], 1e-4);
}

// ---------------------------------------------------------------------------
// 测试：RMSNorm 手动计算验证（含权重）
//
// x = [3, 4], w = [2, 1], eps = 0
// rms = sqrt((9+16)/2) = sqrt(12.5)
// y0 = 3/sqrt(12.5)*2 = 6/sqrt(12.5)
// y1 = 4/sqrt(12.5)*1 = 4/sqrt(12.5)
// ---------------------------------------------------------------------------
TEST (rmsnorm_manual_value) {
    const float x[2] = {3.0f, 4.0f};     // 输入向量
    const float w[2] = {2.0f, 1.0f};      // 权重向量（w0 权重加倍）
    float y[2];

    rmsnorm_ref(x, w, y, 2, 0.0f);       // eps = 0 简化计算

    // rms = sqrt((9+16)/2) = sqrt(12.5)
    // y0 = 3/sqrt(12.5)*2，y1 = 4/sqrt(12.5)
    EXPECT_NEAR(y[0], 6.0 / std::sqrt(12.5), 1e-5);
    EXPECT_NEAR(y[1], 4.0 / std::sqrt(12.5), 1e-5);
}