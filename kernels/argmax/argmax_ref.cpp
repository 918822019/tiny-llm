// ============================================================================
// argmax_ref.cpp — Argmax 算子的参考实现（标量版）
// ============================================================================
// 本文件实现 argmax 算子：找出数组中最大元素的下标。
//
// 数学定义：
//   argmax(x) = arg min { i | x[i] >= x[j], ∀j }
//   即返回使得 x[i] 最大的最小下标 i。
//
// 在 Transformer 中的位置：
//   推理的最后一步——greedy（贪心）解码。lm_head 将 hidden states 映射为
//   词表大小的 logits 向量（Qwen2.5 为 151936 维），argmax 选出分数最高的
//   token 作为下一步输出。每生成一个 token 都要调用一次。
//
// ref 与 neon 版本的关系：
//   - 本文件是标量参考实现，逐个比较 + 维护当前最大值下标。
//   - argmax_neon.cpp 使用两遍法（pass 1 NEON 归约求 max，pass 2 找首个匹配），
//     数值语义逐位一致（max 是精确运算），单测直接断言下标相等。
//
// 平局约定：
//   如果有多个并列最大值，取第一个（用严格 '>' 保证）。
//   这与 numpy/torch 的 argmax 行为一致，且单测有断言；
//   SIMD 重写时必须保持同样行为，否则生成结果不可复现。
//
// 优化要点：
//   1. 单次线性扫描，O(n) 时间复杂度，O(1) 空间。
//   2. 严格 '>' 比较：只在遇到更大值时更新 best，相等时不更新，
//      保证平局时返回靠前的下标。
// ============================================================================

#include "ref_ops.h" // 声明 argmax_ref 等参考算子的头文件

namespace tinyqwen {
  // =========================================================================
  // argmax_ref — Argmax 参考实现
  // =========================================================================
  // 功能：找出 logits 数组中最大值的下标（平局取第一个）
  // 参数：
  //   logits — 输入数组（通常是 lm_head 输出的词表 logits），长度 n
  //   n      — 数组长度（Qwen2.5 词表大小为 151936）
  // 返回值：最大元素的下标（int）
  int argmax_ref(const float *logits, int n) {
    // 初始化最佳下标为 0（假设 n > 0）
    int best = 0;
    // 从下标 1 开始逐个比较
    for (int i = 1; i < n; ++i) {
      // 严格 '>'：只有当前值严格大于已知最大值时才更新
      // 这保证了平局时保留第一个最大值的下标（与 numpy/torch 一致）
      if (logits[i] > logits[best]) {
        best = i; // 更新最佳下标
      }
    }
    return best; // 返回最大值的下标
  }
} // namespace tinyqwen
