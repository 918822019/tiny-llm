// ============================================================================
// matvec_f32_neon.cpp — 矩阵乘向量：y = W @ x —— NEON SIMD 版（aarch64）
// ============================================================================
//
// ============================================================================
// 先建立直觉：什么是 SIMD，为什么它快
// ============================================================================
//
// SIMD = Single Instruction Multiple Data，一条指令同时算多个数据。
// 普通（标量）代码一次只能算一个 float 的乘加：
//
//     acc += row[i] * x[i];          // 1 条乘法 + 1 条加法，处理 1 个元素
//
// NEON 是 ARM 的 SIMD 指令集（Apple Silicon、arm64 Android 都自带）。
// 它有一种 128 位的宽寄存器，正好装 4 个 float（叫一个"向量寄存器"）：
//
//     float32x4_t 寄存器（128 位）
//     ┌─────────┬─────────┬─────────┬─────────┐
//     │ lane 0  │ lane 1  │ lane 2  │ lane 3  │  每个 lane 装一个 float
//     └─────────┴─────────┴─────────┴─────────┘
//
// 一条 NEON 指令对 4 个 lane **同时**运算，等于把上面那行标量代码
// 一次做 4 份。点积这种"大量独立乘加"的循环是 SIMD 的完美猎物——
// 而 decode 阶段几乎全在跑点积（matvec 是绝对热点，见优化手册 §6.6）。
//
// ============================================================================
// SIMD / FMA / 累加：同一行代码的三个侧面（最容易混的三个词，先掰开）
// ============================================================================
//
// 标量点积的一轮：   acc = acc + row[i] * x[i];
// 本实现的一轮：     acc0 = vfmaq_f32(acc0, vld1q_f32(row+i), vld1q_f32(x+i));
//
// 三个词回答三个不同的问题，彼此正交（可以单独出现、任意组合）：
//
//   【SIMD】—— 一条指令处理几个数据？（并行"宽度"）
//     对应代码：vld1q_f32 一次加载 4 个 float；vfmaq_f32 对 4 个 lane
//     同时运算。标量一轮只碰 1 个元素，这里一轮碰 4 个。
//     "一条指令、多份数据"就是 SIMD 的全部含义——它管的是宽度。
//
//   【FMA】—— 一条指令做什么运算？（乘 + 加"融合"）
//     对应代码：vfmaq_f32 里的 fma（fused multiply-add）：把 a*b + acc
//     融合成一条指令、只对最终结果舍入一次。不融合就得 vmulq_f32 乘完
//     再 vaddq_f32 加——两条指令、两次舍入。它管的是运算本身。
//
//   【累加】—— 中间结果存哪、怎么攒成最终点积？（"状态"结构）
//     对应代码：acc0 = vfmaq_f32(acc0, ...)——把上一步的部分和喂回去、
//     结果存回 acc0；再加上"4 个累加器"的布局和函数末尾的合并归约。
//     点积的"攒"发生在这里——它管的是数据怎么流动、存哪。
//
// 正交的证据：标量也能 FMA（C 的 fmaf()）；向量也能不 FMA
// （vmulq_f32 + vaddq_f32 拆开两条）；累加结构跟选什么指令无关。
// 本实现是三者全上：4 路宽（SIMD）× 乘加融合（FMA）× 4 条链攒和（累加）。
//
// 下文读代码时对照：内循环那一行 = SIMD + FMA + 累加三者叠在一起；
// 累加器声明和末尾合并 = 纯累加结构；vld1q/vfmaq 的"q 和 4 lane" = SIMD。

// ============================================================================
// NEON 函数（intrinsic）的命名规则——看懂名字就不用背
// ============================================================================
//
// 形如 vXXXq_f32 的名字拆开读：
//   v     = NEON 指令（vector）
//   XXX   = 干什么：ld1 加载 / dup 复制 / fma 乘加 / add 加法……
//   q     = 操作 128 位宽寄存器（4 个 float）；没有 q 则是 64 位（2 个）
//   f32   = 元素类型是 float32
// 所以 vld1q_f32 = "vector load：从内存连续取 4 个 float 进宽寄存器"。
// 本文件用到的 5 个 intrinsic 都会在出现处逐个解释。
//
// ============================================================================
// 本实现的 5 个要点（数学含义与 matvec_f32_ref 完全一致，只是更快）
// ============================================================================
//
//   1. [SIMD] 向量化：float32x4_t 一次装 4 个 float，vld1q_f32 加载
//      （NEON 加载不要求 16B 对齐，非对齐地址直接用）；
//   2. [FMA] vfmaq_f32(acc, a, b) = acc + a*b，一条指令、只舍入一次
//      （aarch64 的 FMA 是基线指令，不需要额外编译选项）；
//   3. [累加] 4 路展开 + 4 个独立累加器：FMA 延迟约 3~4 周期，单条累加链
//      （acc = vfma(acc,...) 自依赖）会让流水线空转；4 条互不依赖的
//      链让乱序执行把延迟完全重叠。每次迭代 4×4 = 16 个元素在飞；
//   4. [累加] 主循环后合并 4 个累加器，vaddvq_f32 一条指令横向归约成标量；
//   5. [累加·标量] 不足 4 个的尾段用标量补齐——不用 mask、不会越界读。
//
//   （每条的 [标签] 对应上文"SIMD / FMA / 累加"三概念；代码里还有
//     更细的逐行拆解，见 dot_row_neon 内部注释。）
//
// 数值说明：float 累加，误差与 double_2_float 同阶；且 4 条链各自
// 只累加 in_dim/16 项，舍入链比逐元素串行更短。单测以 ref 为门禁。
//
// 平台说明：NEON 是 aarch64（Apple Silicon、Android arm64-v8a）的
// 基线指令集，无需 -march/-mfpu 选项。整个实现包在 __aarch64__ 里：
//   - aarch64 平台（本机、arm64 Android）：正常编译并自注册；
//   - 其他平台（如 x86）：本文件编译为空翻译单元，"neon" 不注册，
//     dispatch 自动兜底到 ref，构建与运行都不受影响。
//
// 选用：--matvec-impl neon / tinyqwen.conf 里 matvec_impl = neon。
// 注意：这里不加 bias；与 ref 相同。
// ============================================================================

#include "dispatch.h" // TINYQWEN_MATVEC_VARIANT 自注册宏
#include "ref_ops.h"  // 辅助函数声明

// 平台开关：只有 aarch64（GCC/Clang 定义 __aarch64__，MSVC 定义 _M_ARM64）
// 才编译下面的实现；其他平台整个文件被预处理器删掉，等于空文件——
// 那里没有 <arm_neon.h>，硬编会直接编译失败。
#if defined(__aarch64__) || defined(_M_ARM64)

#include <arm_neon.h> // NEON intrinsic declarations（编译器自带，非第三方）

#include <cstddef>    // size_t

namespace tinyqwen {
  namespace {
    // ========================================================================
    // dot_row_neon() — W 的一行与 x 的点积：NEON 4 链 FMA
    // ========================================================================
    // 整个 kernel 的内循环，所有优化都发生在这里。
    // 计算的是 row[0]*x[0] + row[1]*x[1] + ... + row[n-1]*x[n-1]，
    // 和标量版完全同一个数学结果，只是把元素 16 个一批地喂给硬件。
    // 参数：
    //   row — 权重行的起始地址（fp32）
    //   x   — 输入向量（fp32）
    //   n   — 向量长度（in_dim）
    // 返回值：点积结果（fp32）
    inline float dot_row_neon(const float *row, const float *x, int n) {
      // ==== 【累加结构·初始化】4 个独立累加器 ============================
      // vdupq_n_f32(v)：dup = duplicate，把标量 v 复制进 4 个 lane，
      // 即构造向量 [v, v, v, v]。这里就是 4 个全零累加器。
      //
      // 为什么要 4 个？先说只有 1 个会怎样：
      //   acc = vfma(acc, ...) 每条都依赖上一条的结果。FMA 从发射到
      //   出结果要 ~3-4 个时钟周期（延迟），下一条必须干等——
      //   好比只有一台咖啡机，每杯要 4 分钟，产量就是 15 分钟 4 杯。
      // 4 条互不依赖的链则像 4 台咖啡机同时开工：乱序执行的 CPU
      //   把 4 条链交错起来，每个周期都有 FMA 在流水线上跑，
      //   延迟被完全重叠——吞吐量顶满。
      // 代价：最后要把 4 个部分和合并起来（见函数末尾，很便宜）。
      float32x4_t acc0 = vdupq_n_f32(0.0f); // 累加器 0：全零 [0,0,0,0]
      float32x4_t acc1 = vdupq_n_f32(0.0f); // 累加器 1
      float32x4_t acc2 = vdupq_n_f32(0.0f); // 累加器 2
      float32x4_t acc3 = vdupq_n_f32(0.0f); // 累加器 3

      int i = 0;
      // ---- 主循环：一次迭代吃 16 个元素（4 条链 × 每条 4 个 lane）----
      // n16 = n 向下取整到 16 的倍数。位运算技巧：15 的二进制是
      // ...001111，~15 就是 ...110000，和 n 做按位与等于抹掉低 4 位。
      // 例：n = 4103 → n16 = 4096。这样循环条件 i < n16 保证
      // row[i..i+15] 永远不越界，循环里不用任何边界检查。
      const int n16 = n & ~15;
      for (; i < n16; i += 16) {
        // ==== 下面这一行 = SIMD + FMA + 累加 三者叠在一起，逐个拆开 ====
        //
        //   acc0 = vfmaq_f32( acc0, vld1q_f32(row+i), vld1q_f32(x+i) );
        //   └─┬─┘  └────┬────┘ └─┬─┘ └───────┬───────┘ └──────┬──────┘
        //   ③累加  ②FMA 运算 ③累加   ①SIMD 加载     ①SIMD 加载
        //          （也是①SIMD：4 lane 并行运算）
        //
        // ① SIMD（宽度）：vld1q_f32(p) 从地址 p 起连续加载 4 个 float，
        //    一条指令（标量要 4 条 load）；vfmaq_f32 对 4 个 lane 同时
        //    运算，一条指令算 4 份乘加（标量要 4 组 mul+add）。
        // ② FMA（运算）：vfmaq_f32 的语义是 acc = acc + a*b，逐 lane：
        //    out[lane] = acc[lane] + a[lane] * b[lane]。"融合"= 乘和加
        //    是一条指令、只对结果舍入一次（先乘后加要两条指令、两次舍入）。
        //    所以这一行展开 = 4 个乘加：acc0 += row[i..i+3] ⊙ x[i..i+3]。
        // ③ 累加（状态）：第一个实参 acc0 把上一步的部分和喂回去，
        //    返回值又存回 acc0——点积就这样一轮轮攒起来。
        //
        // 四条链互不依赖（各写各的 acc），让 CPU 重叠 FMA 延迟
        // （为什么是 4 个累加器，见上面"累加结构"的咖啡机类比）。
        acc0 = vfmaq_f32(acc0, vld1q_f32(row + i), vld1q_f32(x + i));         // 链0: elem[i..i+3]
        acc1 = vfmaq_f32(acc1, vld1q_f32(row + i + 4), vld1q_f32(x + i + 4)); // 链1: elem[i+4..i+7]
        acc2 = vfmaq_f32(acc2, vld1q_f32(row + i + 8), vld1q_f32(x + i + 8)); // 链2: elem[i+8..i+11]
        acc3 = vfmaq_f32(acc3, vld1q_f32(row + i + 12), vld1q_f32(x + i + 12)); // 链3: elem[i+12..i+15]
      }
      // ==== 向量尾段：还剩 4~15 个元素（n 不是 16 的倍数时）====
      // 和主循环同一套 SIMD+FMA+累加，只是每次只开一条链吃 4 个。
      // n4 = n 向下取整到 4 的倍数（抹掉低 2 位）。全部记入 acc0
      // （此刻它和其他链一样已经"完工"，借它用）。
      // 例：n = 4103 → 主循环吃到 4096，这里再吃 4 个到 4100。
      const int n4 = n & ~3;
      for (; i < n4; i += 4) {
        acc0 = vfmaq_f32(acc0, vld1q_f32(row + i), vld1q_f32(x + i));
      }
      // ==== 【累加结构·收敛】把 16 路部分和攒成一个标量 ====
      // 到目前为止部分和散落在 4 个寄存器 × 4 个 lane 里（16 路并行攒出来的），
      // 现在要把它们全部加起来。注意这两步只做加法、没有乘法——纯累加，不含 FMA。
      //
      // vaddq_f32(a, b)：逐 lane 相加，[a0+b0, a1+b1, a2+b2, a3+b3]。
      //   先两两合并：sum01 的每个 lane = 链0 与链1 对应 lane 之和。
      //   （lane 之间互不 mixing，还是 SIMD：一条指令加 4 对。）
      const float32x4_t sum01 = vaddq_f32(acc0, acc1); // sum01[lane] = acc0[lane] + acc1[lane]
      const float32x4_t sum23 = vaddq_f32(acc2, acc3); // sum23[lane] = acc2[lane] + acc3[lane]
      // vaddvq_f32(v)：多了个 "v" = across Vector，横向归约——
      //   把一个向量里的 4 个 lane 加成一个标量：v0+v1+v2+v3。
      //   这一步从"4 路并行"收敛到"1 个数"，SIMD 到此为止。
      float total = vaddvq_f32(vaddq_f32(sum01, sum23)); // total = Σ all 16 partial sums
      // ==== 标量尾段：还剩 0~3 个元素（n 不是 4 的倍数的零头）====
      // 例：n = 4103 → 上面吃到 4100，这里补最后 3 个。
      // 逐个乘加：回到标量世界——没有 SIMD（一次 1 个元素），
      // 累加也是普通标量累加（编译器可能顺手融合成标量 FMA，
      // 但那是它的事，逻辑上就是乘 + 加 + 攒）。不值得再动向量指令，
      // 也绝不会越界读。
      for (; i < n; ++i) {
        total += row[i] * x[i];
      }
      // 数值注：归约的相加顺序（16 路分组）与标量版的逐个串行不同，
      // 浮点加法不满足结合律，所以结果与 ref 有极小的舍入差异——
      // 这正是单测用容差（而非逐位相等）对齐的原因。
      return total;
    }
  } // namespace

  // ========================================================================
  // matvec_f32_neon() — 外层入口
  // ========================================================================
  // 功能：计算 y = W @ x（fp32，NEON 4 链 FMA）
  // 参数：
  //   w       — 权重矩阵，行主序 [out_dim, in_dim]
  //   x       — 输入向量（长度 in_dim）
  //   y       — 输出向量（长度 out_dim）
  //   out_dim — 输出维度
  //   in_dim  — 输入维度
  // 说明：结构与 matvec_f32_ref 完全一致——优化全部封装在 dot_row_neon 里，
  //       这也是"变体与 ref 签名/语义完全相同"纪律的体现：调用方无感。
  void matvec_f32_neon(const float *w, const float *x, float *y, int out_dim, int in_dim) {
    for (int o = 0; o < out_dim; ++o) {
      // 第 o 行起点：跳过前面 o 行（每行 in_dim 个 float）
      const float *row = w + static_cast<size_t>(o) * in_dim;
      // 用 NEON 点积计算该行的输出分量
      y[o] = dot_row_neon(row, x, in_dim);
    }
  }

  // 自注册进 dispatch：main 之前这行就会执行，把 ("neon", 函数指针)
  // 登记进注册表，于是 --matvec-impl neon / 配置 matvec_impl = neon
  // 能按名字找到本实现。仅 aarch64 构建会执行到这里；其他平台
  // "neon" 根本不存在于注册表，选它会报错并列出可用实现（fail fast）。
  TINYQWEN_MATVEC_VARIANT(matvec_f32_neon, "neon");
} // namespace tinyqwen

#endif // defined(__aarch64__) || defined(_M_ARM64)
