#pragma once

// ============================================================================
// 文件: tensor.h
// 作用: 定义 TensorView —— 一个"只读视图"，描述某块权重数据在哪里、什么形状
//
// 核心概念:
//   TensorView 是一个"非拥有（non-owning）视图"——它只记录数据的地址 + 形状，
//   自己不负责分配/释放那块内存。真正的内存属于加载了文件的 ModelFile。
//
// 设计权衡:
//   好处: 零拷贝、零开销，不需要复制权重数据
//   代价: ModelFile 必须比所有用到这个视图的地方活得更久，否则指针就"悬空"了
//        （指向已被释放的内存，读到垃圾数据）
//
// 设计哲学:
//   刻意保持"哑"（dumb object）：只有指针 + shape + dtype，没有引用计数、
//   没有计算逻辑。这样设计使得它在整个推理链路中足够轻量、无副作用。
//
// 前置阅读: docs/infra_primer.md 第 3 节（内存布局与指针）
// ============================================================================

#include <cstdint>
#include <string>

#include "tiny_format.h"

namespace tinyqwen {
    // -------------------------------------------------------------------------
    // TensorView: 张量的非拥有只读视图
    //
    // 说明:
    //   一个 TensorView 描述一块连续内存区域的"元信息"：它叫什么名字、是什么
    //   数据类型、有几个维度、每个维度多大、数据从哪开始、总共多少字节。
    //
    // 使用场景:
    //   - ModelFile 加载 .tqwen 文件后，为每个 tensor 创建 TensorView
    //   - QwenModel 从 ModelFile 获取 TensorView，绑定到 LayerWeights 结构
    //   - 前向计算时通过 TensorView 的 data 指针读取权重数据
    //
    // 注意事项:
    //   - data 指针指向 ModelFile 内部的 data_ buffer，不可释放
    //   - 所有读取操作都是只读的，不会修改数据
    //   - 支持 1-4 维的张量，shape 中未使用的维度填 0
    // -------------------------------------------------------------------------
    struct TensorView {
        // 张量名字，如 "model.layers.0.mlp.up_proj.weight"
        // 与 HuggingFace 格式的命名一致，便于对照
        std::string name;

        // 数据类型: kF32(FP32) / kF16(FP16) / kI4(INT4) 等
        Dtype dtype = Dtype::kF32;

        // 维度数: 1-4，表示 shape 数组中有几个有效维度
        int ndim = 0;

        // 每一维的大小，shape[0..ndim-1] 有效，其余填 0
        // 例如: 形状为 [1024, 896] 的矩阵，ndim=2, shape=[1024, 896, 0, 0]
        uint64_t shape[4] = {0, 0, 0, 0};

        // 指向数据起始位置的只读指针
        // 注意: 内存所有权属于 ModelFile，本视图不负责释放
        const uint8_t *data = nullptr;

        // 数据总字节数 = 元素个数 * 每元素字节数
        // 用于校验和内存边界检查
        uint64_t nbytes = 0;

        // ---------------------------------------------------------------------
        // numel: 计算张量中元素的总个数
        //
        // 计算方式: shape[0] * shape[1] * ... * shape[ndim-1]
        // 例如: 形状 [2, 3, 4] 的 numel = 2 * 3 * 4 = 24
        //
        // 返回值:
        //   张量中所有元素的总数
        // ---------------------------------------------------------------------
        uint64_t numel() const;

        // ---------------------------------------------------------------------
        // dim: 获取第 i 维的大小
        //
        // 参数:
        //   i: 维度索引（0-based）
        //
        // 返回值:
        //   第 i 维的大小；越界时安全地返回 1（相当于"这一维不存在"）
        //
        // 说明:
        //   返回 1 而非 0 的设计是为了方便广播语义：在维度不匹配时，
        //   缺失的维度视为大小为 1，不会导致乘法结果为零。
        // ---------------------------------------------------------------------
        uint64_t dim(int i) const { return (i >= 0 && i < ndim) ? shape[i] : 1; }

        // ---------------------------------------------------------------------
        // f32: 按 float 类型获取数据指针
        //
        // 返回值:
        //   指向数据的 const float* 指针
        //
        // 说明:
        //   如果实际 dtype 不是 kF32，说明程序逻辑有误（例如把 INT4 权重当 FP32 读），
        //   直接 abort 大声失败（fail fast 原则，见 primer 第 9 节）。
        //   这种设计避免静默读到错误数据后产生难以排查的数值偏差。
        // ---------------------------------------------------------------------
        const float *f32() const;
    };
} // namespace tinyqwen