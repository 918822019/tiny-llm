#pragma once

// ============================================================================
// 文件: config.h
// 作用: 极简配置加载器 —— 读 `key = value` 形式的纯文本配置文件
//
// 设计理念:
//   刻意不用 YAML/JSON 库（零依赖），配置项很少，手写解析最简单可控。
//   配置文件格式: 每行一个 key = value 对，# 开头的行为注释。
//
// 优先级约定:
//   CLI 开关 > 配置文件 > 默认值
//   这样 benchmark 时可以随时用命令行覆盖配置里的值。
//
// 使用示例:
//   Config cfg;
//   std::string err;
//   cfg.load("model.conf", &err);
//   std::string model_path = cfg.get("model_path", "/data/qwen.tqwen");
// ============================================================================

#include <cstddef>
#include <string>
#include <unordered_map>

namespace tinyqwen {
    // -------------------------------------------------------------------------
    // Config 类: 键值对配置管理器
    //
    // 功能:
    //   - 从文件中读取 key = value 形式的配置
    //   - 支持通过 key 查询配置值，不存在的 key 返回默认值
    //   - 支持查询 key 是否存在和配置项数量
    //
    // 内部存储:
    //   使用 std::unordered_map 存储键值对，查找 O(1) 平均复杂度
    // -------------------------------------------------------------------------
    class Config {
    public:
        // ---------------------------------------------------------------------
        // load: 读取配置文件
        //
        // 参数:
        //   path: 配置文件路径
        //   err:  输出参数，失败时写入错误原因（fail fast 策略）
        //
        // 返回值:
        //   成功返回 true，失败返回 false 并把原因写进 *err
        //
        // 说明:
        //   解析逻辑: 逐行读取，跳过空行和 # 开头的注释行，
        //   按 = 分割每行得到 key 和 value，trim 前后空格后存入 kv_。
        //   重复的 key 后面的值会覆盖前面的值。
        // ---------------------------------------------------------------------
        bool load(const std::string &path, std::string *err);

        // ---------------------------------------------------------------------
        // get: 查询配置项的值
        //
        // 参数:
        //   key:          配置项的键名
        //   default_value: 当 key 不存在时返回的默认值
        //
        // 返回值:
        //   配置项的值（字符串），key 不存在时返回 default_value
        // ---------------------------------------------------------------------
        std::string get(const std::string &key, const std::string &default_value) const;

        // ---------------------------------------------------------------------
        // has: 检查指定 key 是否存在
        //
        // 参数:
        //   key: 配置项的键名
        //
        // 返回值:
        //   存在返回 true，不存在返回 false
        // ---------------------------------------------------------------------
        bool has(const std::string &key) const;

        // ---------------------------------------------------------------------
        // size: 返回当前配置项的数量
        //
        // 返回值:
        //   已加载的配置项个数
        // ---------------------------------------------------------------------
        size_t size() const { return kv_.size(); }

    private:
        // 内部存储: 键值对映射表，key 为配置项名，value 为配置项值
        std::unordered_map<std::string, std::string> kv_;
    };
} // namespace tinyqwen